    fun getRestroomsForRegion(regionId: String): List<RestroomEntity> {
        return when (regionId) {
            AlgerianRegions.REGION_CENTRE.id -> centreRestrooms
            AlgerianRegions.REGION_OUEST.id -> ouestRestrooms
            AlgerianRegions.REGION_EST.id -> estRestrooms
            AlgerianRegions.REGION_HAUTS_PLATEAUX.id -> hautsPlateauxRestrooms
            AlgerianRegions.REGION_SUD.id -> sudRestrooms
            else -> emptyList()
        }
    }

    fun getAllRegionalRestrooms(): List<RestroomEntity> {
        return centreRestrooms + ouestRestrooms + estRestrooms + hautsPlateauxRestrooms + sudRestrooms
    }

    fun getRestroomsForWilaya(wilayaName: String): List<RestroomEntity> {
        val trimmed = wilayaName.trim().removePrefix("ولاية ").trim()
        return getAllRegionalRestrooms().filter {
            it.wilaya.equals(trimmed, ignoreCase = true) || it.wilaya.equals(wilayaName, ignoreCase = true)
        }
    }

